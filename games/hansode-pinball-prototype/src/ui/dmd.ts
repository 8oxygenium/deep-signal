export const DMD_W = 200;
export const DMD_H = 44;

export class Dmd {
  readonly canvas: HTMLCanvasElement;
  private g: CanvasRenderingContext2D;
  /** 0..1 の明るさ */
  readonly buf = new Float32Array(DMD_W * DMD_H);
  private pitch = 3;
  color = '#ff8a1e';
  private rgb: [number, number, number] = [255, 138, 30];

  constructor() {
    this.canvas = document.createElement('canvas');
    this.canvas.className = 'dmd';
    this.g = this.canvas.getContext('2d')!;
    this.setPitch(3);
  }

  setPitch(p: number): void {
    this.pitch = p;
    this.canvas.width = DMD_W * p;
    this.canvas.height = DMD_H * p;
  }

  setColor(c: string): void {
    this.color = c;
    const m = /^#?([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(c);
    if (m) this.rgb = [parseInt(m[1], 16), parseInt(m[2], 16), parseInt(m[3], 16)];
  }

  clear(): void {
    this.buf.fill(0);
  }

  dot(x: number, y: number, v = 1): void {
    x = Math.round(x);
    y = Math.round(y);
    if (x < 0 || y < 0 || x >= DMD_W || y >= DMD_H) return;
    const i = y * DMD_W + x;
    if (v > this.buf[i]) this.buf[i] = v;
  }

  rect(x: number, y: number, w: number, h: number, v = 1): void {
    for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) this.dot(x + i, y + j, v);
  }

  textWidth(s: string, scale = 1): number {
    return s.length * 6 * scale - scale;
  }

  text(s: string, x: number, y: number, scale = 1, align: 'left' | 'center' | 'right' = 'left', v = 1): void {
    const str = s.toUpperCase().replace(/X(?=\d)/g, 'x');
    const w = this.textWidth(str, scale);
    let cx = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
    for (const ch of str) {
      const rows = F[ch] ?? F['?'];
      for (let r = 0; r < 7; r++) {
        const bits = rows[r];
        for (let c = 0; c < 5; c++) {
          if (bits & (1 << (4 - c))) this.rect(cx + c * scale, y + r * scale, scale, scale, v);
        }
      }
      cx += 6 * scale;
    }
  }

  /** 収まる大きさで真ん中に書く */
  fitText(s: string, y: number, maxScale: number, v = 1): number {
    let sc = maxScale;
    while (sc > 1 && this.textWidth(s.toUpperCase(), sc) > DMD_W - 4) sc--;
    this.text(s, DMD_W / 2, y, sc, 'center', v);
    return sc;
  }

  present(): void {
    const g = this.g;
    const p = this.pitch;
    g.fillStyle = '#050403';
    g.fillRect(0, 0, this.canvas.width, this.canvas.height);
    const [r, gg, b] = this.rgb;
    const off = `rgba(${r},${gg},${b},0.07)`;
    const r0 = p * 0.42;
    for (let y = 0; y < DMD_H; y++) {
      for (let x = 0; x < DMD_W; x++) {
        const v = this.buf[y * DMD_W + x];
        g.fillStyle = v > 0.02 ? `rgba(${r},${gg},${b},${0.15 + v * 0.85})` : off;
        g.fillRect(x * p + (p - r0 * 2) / 2, y * p + (p - r0 * 2) / 2, r0 * 2, r0 * 2);
      }
    }
  }
}

export function fmt(n: number): string {
  return Math.floor(n).toLocaleString('en-US');
}
